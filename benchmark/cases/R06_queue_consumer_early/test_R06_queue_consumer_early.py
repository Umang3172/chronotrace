"""R06 queue_consumer_early: the consumer drains the queue before the producer enqueues."""

import asyncio

import pytest

from benchmark.support import io_latency
from chronotrace.capture.instrument import assertion, operation
from chronotrace.schedule.harness import ScheduleHarness, force_order

_chronotrace_gate_enqueue_job = asyncio.Event()


@pytest.fixture(autouse=True)
def _chronotrace_reset_enqueue_job():
    """Provide a fresh synchronization gate for each test."""
    global _chronotrace_gate_enqueue_job
    _chronotrace_gate_enqueue_job = asyncio.Event()
    yield


QUEUE: list[str] = []


@operation("enqueue_job", resource="queue.items", access="write")
async def enqueue_job(job: str) -> None:
    """Append a job to the work queue."""
    QUEUE.append(job)
    _chronotrace_gate_enqueue_job.set()


@operation("drain_queue", resource="queue.items", access="read")
async def drain_queue() -> list[str]:
    """Take everything currently queued."""
    await _chronotrace_gate_enqueue_job.wait()
    taken = list(QUEUE)
    QUEUE.clear()
    return taken


async def producer() -> None:
    """Enqueue one job once its payload has been fetched."""
    await io_latency()
    await enqueue_job("job-1")


@pytest.mark.asyncio
async def test_consumer_drains_produced_job() -> None:
    QUEUE.clear()
    task = asyncio.create_task(producer())
    await io_latency()
    drained = await drain_queue()
    with assertion("queue.items"):
        assert drained == ["job-1"]
    await task


@pytest.mark.asyncio
async def test_chronotrace_regression_765b949a() -> None:
    """Reproduce the interleaving that used to fail, deterministically.

    Generated by ChronoTrace for incident 765b949a. Before the repair this
    race appeared in roughly 60% of runs; this guard forces the
    exact ordering that caused it, so a regression fails here on every run
    rather than once in a while.
    """
    forced_order = ['drain_queue#0', 'enqueue_job#0']
    harness = ScheduleHarness(forced_order, timeout_s=5.0)
    with force_order(harness):
        await test_consumer_drains_produced_job()
    assert harness.reached == forced_order
